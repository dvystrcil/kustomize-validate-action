#!/usr/bin/env bash
# Regenerate schemas/cluster/ from every CRD the cluster serves (#22).
#
#   tools/refresh-cluster-schemas.sh        # current kube context; needs `get crd`
#
# Then open a PR with the diff. Run it after installing or upgrading an
# operator; a stale bundle only means a NEW field is reported as unknown (the
# datree catalog's failure mode, but measured against this cluster), and a CRD
# shipped in a repo's own render always wins over this bundle.
#
# The repo is PUBLIC: SOURCE.md records the date and counts only, never the
# context or API server address. The schemas are the operators' own public CRDs.
# PYTHON must have pyyaml (default python3).
set -euo pipefail
cd "$(dirname "$0")/.."
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
kubectl get crd -o json > "$tmp/crds.json"
n="$(jq '.items | length' "$tmp/crds.json")"
[ "$n" -gt 0 ] || { echo "FATAL: the cluster returned no CRDs; refusing to write an empty bundle" >&2; exit 1; }
"${PYTHON:-python3}" crd_schemas.py "$tmp/out" "$tmp/crds.json"
m="$(find "$tmp/out" -name '*.json' | wc -l)"
cat > "$tmp/out/SOURCE.md" <<MD
# schemas/cluster

Generated by \`tools/refresh-cluster-schemas.sh\` on $(date -u +%Y-%m-%d) from the
homelab cluster's served CRDs: $n CRDs, $m schema files (one per served
version). Do not edit by hand; re-run the script.
MD
rm -rf schemas/cluster && mkdir -p schemas && mv "$tmp/out" schemas/cluster
echo "schemas/cluster: $n CRDs -> $m schemas"
